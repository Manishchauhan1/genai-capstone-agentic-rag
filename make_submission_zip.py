"""Builds the submission zip without secrets or junk (FR-10).

Run from the project folder:  python make_submission_zip.py
The zip is written next to the project folder as agentic-doc-qa-submission.zip.

It refuses to build if the GROQ_API_KEY value from your .env, or anything shaped like
a Groq key (gsk_...), appears inside any file that would be included.
"""

import os
import re
import zipfile
from pathlib import Path

from dotenv import dotenv_values

from docqa.errors import DocQAError

EXCLUDED_DIRS = {".venv", "venv", "env", ".git", "__pycache__", ".pytest_cache", ".superpowers",
                 ".vscode", ".idea"}
EXCLUDED_FILES = {".env", ".streamlit/secrets.toml", ".DS_Store"}
KEY_PATTERN = re.compile(rb"gsk_[A-Za-z0-9]{20,}")  # the shape of a Groq key
EXCLUDED_PREFIXES = ("tests/fixtures/",)  # regenerated by the tests


def _included_files(project_dir: Path) -> list[str]:
    names = []
    for folder, subfolders, files in os.walk(project_dir):
        subfolders[:] = [name for name in subfolders if name not in EXCLUDED_DIRS]
        for file in files:
            relative = (Path(folder) / file).relative_to(project_dir).as_posix()
            if (
                relative in EXCLUDED_FILES
                or (relative.startswith(".env.") and relative != ".env.example")
                or relative.endswith(".zip")
                or relative.startswith(EXCLUDED_PREFIXES)
            ):
                continue
            names.append(relative)
    return sorted(names)


def build_zip(project_dir: Path, out_path: Path) -> list[str]:
    """Write the zip and return the names it contains."""
    project_dir, out_path = Path(project_dir), Path(out_path)
    names = _included_files(project_dir)

    env_file = project_dir / ".env"
    key = (dotenv_values(env_file).get("GROQ_API_KEY") or "").strip() if env_file.exists() else ""
    for name in names:
        content = (project_dir / name).read_bytes()
        if (key and key.encode() in content) or KEY_PATTERN.search(content):
            raise DocQAError(f"Possible API key found in {name}. Remove it before submitting.")

    with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED) as archive:
        for name in names:
            archive.write(project_dir / name, arcname=name)
    return names


if __name__ == "__main__":
    here = Path(__file__).resolve().parent
    target = here.parent / "agentic-doc-qa-submission.zip"
    included = build_zip(here, target)
    print(f"Wrote {target} with {len(included)} files.")
